# Slicing ya Indexing karni hai to 

# Short Name Chaiye To 
b = "Daksh Khandelwal "

bb = b[0:6]  # start from index 0 all the way till 6 (excluding 6)
print(bb)

bbb = b[-11:-1]  # start from index -11 all the way till -1 (excluding -1)
print(bbb)

# Character chahiye to 
bbbb = b[2] # index 1 will show i.e 'k'  # Character 2 

print(bbbb)