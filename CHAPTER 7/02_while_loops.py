i = 1
while(i <= 50):  # It can be while(i < 6) as well
    print(i)
    i += 1 # It can be i = i + 1 as well

'''
Output:
1   
2
3
4
5
'''

# Note: While loops are used when the number of iterations is not known beforehand. The loop continues until the condition becomes false. In this case, the loop will continue to print numbers from 1 to 50 until the condition i <= 50 is no longer true.